def _evidence_html(evidence_list: list[dict]) -> str:
    if not evidence_list:
        return ""
    rows = []
    for ev in evidence_list:
        if ev.get("transition_from", "").startswith("["):
            continue  # skip spatial placeholders
        badge_cls = _BADGE.get(ev.get("strength", "insufficient data"), "badge-insuf")
        rows.append(
            f"<tr><td>{ev.get('transition_from', '')}</td>"
            f"<td>{ev.get('transition_to', '')}</td>"
            f"<td>{ev.get('claim', '')}</td>"
            f"<td><span class='{badge_cls}'>{ev.get('strength', '')}</span></td>"
            f"<td>{ev.get('effect_size', '')}</td></tr>"
        )
    if not rows:
        return ""
    return (
        "<h2>Evidence</h2>"
        "<table><thead><tr><th>From</th><th>To</th><th>Claim</th>"
        "<th>Strength</th><th>Effect size</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table>"
    )


