# ── Chart generation (matplotlib) ─────────────────────────────────────────────

def _mpl_setup() -> tuple:
    """Import and configure matplotlib for off-screen rendering."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt  # noqa: PLC0415
    return plt


def _generate_trend_chart_png(stats_list: list[dict]) -> bytes | None:
    """Two-panel line chart: major classes (top) and minor classes (bottom) on separate axes."""
    try:
        plt = _mpl_setup()
        if len(stats_list) < 2:
            return None

        sorted_stats = sorted(stats_list, key=lambda s: s["year"])
        years = [s["year"] for s in sorted_stats]

        all_codes = sorted({
            c["code"] for s in sorted_stats for c in s["classes"] if c["code"] != 0
        })

        major_codes: set[int] = set()
        for stat in sorted_stats:
            total = sum(c["area_km2"] for c in stat["classes"] if c["code"] != 0)
            if total <= 0:
                continue
            for cls in stat["classes"]:
                if cls["code"] != 0 and (cls["area_km2"] / total) * 100 >= 5:
                    major_codes.add(cls["code"])
        minor_codes = [c for c in all_codes if c not in major_codes]

        major_sorted = sorted(
            major_codes,
            key=lambda c: sum(
                next((x["area_km2"] for x in s["classes"] if x["code"] == c), 0)
                for s in sorted_stats
            ),
            reverse=True,
        )

        def _get_areas(code: int) -> list[float]:
            return [
                next((c["area_km2"] for c in s["classes"] if c["code"] == code), 0.0)
                for s in sorted_stats
            ]

        def _style_ax(ax) -> None:
            ax.grid(True, alpha=0.3, color="#e5e7eb")
            ax.set_xticks(years)
            ax.tick_params(colors="#6b7280", labelsize=9)
            ax.set_ylabel("Area (km²)", fontsize=9, color="#374151")
            for spine in ax.spines.values():
                spine.set_edgecolor("#e5e7eb")

        has_minor = bool(minor_codes)
        fig_h = 9 if has_minor else 5
        if has_minor:
            fig, (ax_maj, ax_min) = plt.subplots(
                2, 1, figsize=(10, fig_h),
                gridspec_kw={"hspace": 0.45, "height_ratios": [3, 2]},
            )
        else:
            fig, ax_maj = plt.subplots(figsize=(10, fig_h))
            ax_min = None

        fig.patch.set_facecolor("white")

        # ── Top panel: major classes ─────────────────────────────────────────
        ax_maj.set_facecolor("#f8fafc")
        ax_maj.set_title(
            "Land Cover Area Trend — Major Classes (larger area)",
            fontsize=11, fontweight="bold", color="#1a4a7a", pad=6,
        )
        for code in major_sorted:
            areas  = _get_areas(code)
            name   = CLASS_NAMES.get(code, f"Class {code}")
            colour = _MPL_COLOURS.get(code, "#888")
            ax_maj.plot(years, areas, label=name, color=colour,
                        linewidth=2, marker="o", markersize=5, zorder=3)
            ax_maj.annotate(
                f"{areas[-1]:,.0f}",
                xy=(years[-1], areas[-1]),
                xytext=(5, 0), textcoords="offset points",
                fontsize=7, color=colour, va="center",
            )
        ax_maj.legend(loc="upper right", fontsize=8, ncol=2,
                      framealpha=0.9, edgecolor="#e5e7eb", title="Class",
                      title_fontsize=7)
        _style_ax(ax_maj)

        # ── Bottom panel: minor classes ───────────────────────────────────────
        if ax_min is not None and minor_codes:
            ax_min.set_facecolor("#f8fafc")
            ax_min.set_title(
                "Minor Classes (smaller area)",
                fontsize=10, fontweight="bold", color="#374151", pad=6,
            )
            for code in minor_codes:
                areas  = _get_areas(code)
                name   = CLASS_NAMES.get(code, f"Class {code}")
                colour = _MPL_COLOURS.get(code, "#888")
                ax_min.plot(years, areas, label=name, color=colour,
                            linewidth=1.8, marker="s", markersize=4, zorder=3)
            ax_min.legend(loc="upper right", fontsize=7.5, ncol=2,
                          framealpha=0.9, edgecolor="#e5e7eb", title="Class",
                          title_fontsize=7)
            ax_min.set_xlabel("Year", fontsize=9, color="#374151")
            _style_ax(ax_min)
        elif ax_min is None:
            ax_maj.set_xlabel("Year", fontsize=9, color="#374151")

        fig.suptitle("", fontsize=1)  # suppress auto-title spacing
        plt.tight_layout()
        buf = io.BytesIO()
        fig.savefig(buf, format="png", dpi=150, bbox_inches="tight")
        plt.close(fig)
        buf.seek(0)
        return buf.read()
    except Exception as exc:
        logger.warning("Could not generate trend chart: %s", exc)
        return None


def _generate_forest_trend_png(stats_list: list[dict]) -> bytes | None:
    """Line chart: forest vs non-forest area over years."""
    try:
        plt = _mpl_setup()
        if len(stats_list) < 2:
            return None

        sorted_stats = sorted(stats_list, key=lambda s: s["year"])
        years = [s["year"] for s in sorted_stats]
        forest_km2  = []
        nonforest_km2 = []
        for stat in sorted_stats:
            f  = sum(c["area_km2"] for c in stat["classes"] if c["code"] in _FOREST_CODES_RPT)
            nf = sum(c["area_km2"] for c in stat["classes"]
                     if c["code"] != 0 and c["code"] not in _FOREST_CODES_RPT)
            forest_km2.append(f)
            nonforest_km2.append(nf)

        fig, ax = plt.subplots(figsize=(10, 4))
        fig.patch.set_facecolor("#f8fafc")
        ax.set_facecolor("#f8fafc")

        ax.plot(years, forest_km2, label="Forest Area", color="#2d6a4f",
                linewidth=2.5, marker="o", markersize=6, zorder=3)
        ax.plot(years, nonforest_km2, label="Non-Forest Area", color="#9e9e9e",
                linewidth=2.5, marker="o", markersize=6, zorder=3)

        ax.set_xlabel("Year", fontsize=10, color="#374151")
        ax.set_ylabel("Area (km²)", fontsize=10, color="#374151")
        ax.set_title("Forest vs Non-Forest Cover Trend",
                     fontsize=12, fontweight="bold", color="#1a4a7a", pad=10)
        ax.legend(loc="right", fontsize=9, framealpha=0.9, edgecolor="#e5e7eb")
        ax.grid(True, alpha=0.3, color="#e5e7eb")
        ax.set_xticks(years)
        ax.tick_params(colors="#6b7280", labelsize=9)
        for spine in ax.spines.values():
            spine.set_edgecolor("#e5e7eb")

        plt.tight_layout()
        buf = io.BytesIO()
        fig.savefig(buf, format="png", dpi=150, bbox_inches="tight",
                    facecolor=fig.get_facecolor())
        plt.close(fig)
        buf.seek(0)
        return buf.read()
    except Exception as exc:
        logger.warning("Could not generate forest chart: %s", exc)
        return None


def _generate_change_chart_png(matrices: list[dict]) -> bytes | None:
    """Horizontal bar chart: net km² change by class."""
    try:
        plt = _mpl_setup()
        if not matrices:
            return None

        matrix = matrices[0]
        net = sorted(
            [n for n in matrix.get("net_change", []) if abs(n["delta_km2"]) > 0.01],
            key=lambda n: n["delta_km2"],
        )
        if not net:
            return None

        labels  = [CLASS_NAMES.get(n["code"], n["class_name"]) for n in net]
        deltas  = [n["delta_km2"] for n in net]
        colours = ["#16a34a" if d > 0 else "#dc2626" for d in deltas]
        max_abs = max(abs(d) for d in deltas) or 1

        fig_h = max(3.0, 0.45 * len(net) + 1.5)
        fig, ax = plt.subplots(figsize=(9, fig_h))
        fig.patch.set_facecolor("#f8fafc")
        ax.set_facecolor("#f8fafc")

        bars = ax.barh(labels, deltas, color=colours, height=0.6, zorder=3)
        ax.axvline(0, color="#374151", linewidth=0.8, zorder=4)
        ax.set_xlabel("Net Change (km²)", fontsize=10, color="#374151")
        ax.set_title(
            f"Net Land Cover Change: {matrix['from_year']}–{matrix['to_year']}",
            fontsize=12, fontweight="bold", color="#1a4a7a", pad=10,
        )
        ax.grid(True, axis="x", alpha=0.3, color="#e5e7eb")
        ax.tick_params(colors="#6b7280", labelsize=9)
        for spine in ax.spines.values():
            spine.set_edgecolor("#e5e7eb")

        offset = max_abs * 0.02
        for bar, delta in zip(bars, deltas):
            sign = "+" if delta > 0 else ""
            ax.text(
                bar.get_width() + (offset if delta >= 0 else -offset),
                bar.get_y() + bar.get_height() / 2,
                f"{sign}{delta:,.1f}",
                va="center", ha="left" if delta >= 0 else "right",
                fontsize=7.5, color="#374151",
            )

        plt.tight_layout()
        buf = io.BytesIO()
        fig.savefig(buf, format="png", dpi=150, bbox_inches="tight",
                    facecolor=fig.get_facecolor())
        plt.close(fig)
        buf.seek(0)
        return buf.read()
    except Exception as exc:
        logger.warning("Could not generate change chart: %s", exc)
        return None


def _generate_sankey_png(matrices: list[dict]) -> bytes | None:
    """Full alluvial Sankey including stable (same-class) flows using matplotlib bezier patches."""
    try:
        import matplotlib.patches as mpatches  # noqa: PLC0415
        from matplotlib.path import Path as MPath  # noqa: PLC0415

        plt = _mpl_setup()
        if not matrices:
            return None

        matrix = matrices[0]
        transitions = [
            t for t in matrix.get("transitions", [])
            if t.get("area_km2", 0) >= 0.5
        ]
        if not transitions:
            return None

        # Collect unique codes and their totals for sizing
        src_totals: dict[int, float] = {}
        tgt_totals: dict[int, float] = {}
        for t in transitions:
            fc, tc, a = t["from_code"], t["to_code"], t["area_km2"]
            src_totals[fc] = src_totals.get(fc, 0) + a
            tgt_totals[tc] = tgt_totals.get(tc, 0) + a

        src_codes = sorted(src_totals, key=lambda c: -src_totals[c])
        tgt_codes = sorted(tgt_totals, key=lambda c: -tgt_totals[c])
        total_area = sum(src_totals.values()) or 1.0

        # Layout constants (data coordinates: x ∈ [0,1], y ∈ [0,1])
        NODE_W = 0.025
        NODE_PAD = 0.018
        MARGIN_L = 0.22   # space for left labels
        MARGIN_R = 0.22
        FLOW_X0 = MARGIN_L + NODE_W
        FLOW_X1 = 1.0 - MARGIN_R - NODE_W
        AVAIL_H = 1.0 - 0.04  # 2% top + bottom margin

        def _place_nodes(codes: list[int], totals: dict[int, float]) -> dict[int, tuple[float, float]]:
            node_heights = {c: max((totals[c] / total_area) * AVAIL_H, 0.008) for c in codes}
            total_h = sum(node_heights[c] for c in codes) + (len(codes) - 1) * NODE_PAD
            start_y = 0.02 + max(0.0, (AVAIL_H - total_h) / 2)
            pos: dict[int, tuple[float, float]] = {}
            y = start_y
            for c in codes:
                h = node_heights[c]
                pos[c] = (y, h)   # (y_bottom, height)
                y += h + NODE_PAD
            return pos

        src_pos = _place_nodes(src_codes, src_totals)
        tgt_pos = _place_nodes(tgt_codes, tgt_totals)

        # Cursor tracks consumed height within each node
        src_cursor = {c: src_pos[c][0] for c in src_codes}
        tgt_cursor = {c: tgt_pos[c][0] for c in tgt_codes}

        fig_h = max(5.5, len(max(src_codes, tgt_codes, key=len if hasattr(len, '__call__') else lambda _: 0)) * 0.35 + 2)
        n_nodes = max(len(src_codes), len(tgt_codes))
        fig_h = max(5.5, n_nodes * 0.55 + 2.5)
        fig, ax = plt.subplots(figsize=(10, fig_h))
        fig.patch.set_facecolor("white")
        ax.set_facecolor("white")
        ax.set_xlim(0, 1)
        ax.set_ylim(0, 1)
        ax.axis("off")

        ax.set_title(
            f"Land Cover Transitions — {matrix.get('from_year', '?')} → {matrix.get('to_year', '?')}\n"
            f"(All transitions ≥ 0.5 km² including stable cover)",
            fontsize=11, fontweight="bold", color="#1a4a7a", pad=8,
        )

        cpX = (FLOW_X1 - FLOW_X0) * 0.45

        # Sort transitions: stable (same-class) first so they render under cross-class flows
        sorted_transitions = sorted(
            transitions,
            key=lambda t: (0 if t["from_code"] == t["to_code"] else 1, -t["area_km2"]),
        )

        for t in sorted_transitions:
            fc, tc, area = t["from_code"], t["to_code"], t["area_km2"]
            h = max((area / total_area) * AVAIL_H, 0.001)

            sx = FLOW_X0
            tx = FLOW_X1
            sy = src_cursor.get(fc, 0)
            ty = tgt_cursor.get(tc, 0)

            src_cursor[fc] = sy + h
            tgt_cursor[tc] = ty + h

            colour = _MPL_COLOURS.get(fc, "#888888")
            is_stable = (fc == tc)
            alpha = 0.55 if is_stable else 0.32

            # Bezier quad: left edge top → right edge top → right edge bottom → left edge bottom
            verts = [
                (sx, sy),                        # MOVETO: left top
                (sx + cpX, sy), (tx - cpX, ty), (tx, ty),   # CURVE4: top ribbon
                (tx, ty + h),                    # LINETO: right bottom
                (tx - cpX, ty + h), (sx + cpX, sy + h), (sx, sy + h),  # CURVE4: bottom ribbon
                (sx, sy),                        # CLOSEPOLY
            ]
            codes = [
                MPath.MOVETO,
                MPath.CURVE4, MPath.CURVE4, MPath.CURVE4,
                MPath.LINETO,
                MPath.CURVE4, MPath.CURVE4, MPath.CURVE4,
                MPath.CLOSEPOLY,
            ]
            path = MPath(verts, codes)
            patch = mpatches.PathPatch(
                path, facecolor=colour, alpha=alpha,
                edgecolor=colour, linewidth=0.3,
            )
            ax.add_patch(patch)

        # Draw nodes and labels
        for code in src_codes:
            y0, h = src_pos[code]
            colour = _MPL_COLOURS.get(code, "#888888")
            rect = mpatches.FancyBboxPatch(
                (MARGIN_L, y0), NODE_W, h,
                boxstyle="square,pad=0", facecolor=colour, edgecolor="white", linewidth=0.5,
            )
            ax.add_patch(rect)
            label = CLASS_NAMES.get(code, f"Class {code}")
            area_km2 = src_totals.get(code, 0)
            ax.text(
                MARGIN_L - 0.012, y0 + h / 2,
                f"{label}\n{area_km2:,.0f} km²",
                ha="right", va="center", fontsize=7.5,
                color="#1e293b", linespacing=1.3,
            )

        for code in tgt_codes:
            y0, h = tgt_pos[code]
            colour = _MPL_COLOURS.get(code, "#888888")
            x0 = 1.0 - MARGIN_R - NODE_W
            rect = mpatches.FancyBboxPatch(
                (x0, y0), NODE_W, h,
                boxstyle="square,pad=0", facecolor=colour, edgecolor="white", linewidth=0.5,
            )
            ax.add_patch(rect)
            label = CLASS_NAMES.get(code, f"Class {code}")
            area_km2 = tgt_totals.get(code, 0)
            ax.text(
                x0 + NODE_W + 0.012, y0 + h / 2,
                f"{label}\n{area_km2:,.0f} km²",
                ha="left", va="center", fontsize=7.5,
                color="#1e293b", linespacing=1.3,
            )

        # Year column headers
        ax.text(MARGIN_L + NODE_W / 2, 0.985, str(matrix.get("from_year", "")),
                ha="center", va="top", fontsize=9, color="#6b7280", fontweight="bold")
        ax.text(1.0 - MARGIN_R - NODE_W / 2, 0.985, str(matrix.get("to_year", "")),
                ha="center", va="top", fontsize=9, color="#6b7280", fontweight="bold")

        plt.tight_layout(rect=[0, 0, 1, 0.97])
        buf = io.BytesIO()
        fig.savefig(buf, format="png", dpi=150, bbox_inches="tight")
        plt.close(fig)
        buf.seek(0)
        return buf.read()
    except Exception as exc:
        logger.warning("Could not generate Sankey chart: %s", exc)
        return None


def _charts_html(stats_list: list[dict], matrices: list[dict], fig_offset: int = 3) -> str:
    import base64  # noqa: PLC0415

    sections: list[str] = []
    n = fig_offset

    trend_png = _generate_trend_chart_png(stats_list)
    if trend_png:
        n += 1
        b64 = base64.b64encode(trend_png).decode()
        sections.append(
            f"""<div class="chart-block">
  <h3>Figure {n} — Land Cover Area Trend (Major &amp; Minor Classes)</h3>
  <img src="data:image/png;base64,{b64}" alt="Land cover area trend"/>
  <p class="chart-caption">
    Area (km²) per land cover class over the full analysis period.
    Major classes (≥5% share in any year) are shown as individual coloured lines;
    minor classes are aggregated as "Others" (dashed grey line).
    Values at right are the latest-year totals.
  </p>
</div>"""
        )

    forest_png = _generate_forest_trend_png(stats_list)
    if forest_png:
        n += 1
        b64 = base64.b64encode(forest_png).decode()
        sections.append(
            f"""<div class="chart-block">
  <h3>Figure {n} — Forest vs Non-Forest Cover Trend</h3>
  <img src="data:image/png;base64,{b64}" alt="Forest vs non-forest trend"/>
  <p class="chart-caption">
    Forest area (Forest, Open Woodland — codes 4, 9)
    versus all other land cover classes over time.
    Source: ICIMOD Nepal Land Cover · equal-area projection EPSG:32645.
  </p>
</div>"""
        )

    change_png = _generate_change_chart_png(matrices)
    if change_png:
        n += 1
        b64 = base64.b64encode(change_png).decode()
        sections.append(
            f"""<div class="chart-block">
  <h3>Figure {n} — Net Change by Land Cover Class</h3>
  <img src="data:image/png;base64,{b64}" alt="Net change bar chart"/>
  <p class="chart-caption">
    Net gain (green) or loss (red) in km² per land cover class over the analysis period.
    Classes with change &lt;0.01 km² are omitted.
  </p>
</div>"""
        )

    sankey_png = _generate_sankey_png(matrices)
    if sankey_png:
        n += 1
        b64 = base64.b64encode(sankey_png).decode()
        from_y = matrices[0]["from_year"] if matrices else "?"
        to_y   = matrices[0]["to_year"]   if matrices else "?"
        sections.append(
            f"""<div class="chart-block">
  <h3>Figure {n} — Land Cover Transition Flow ({from_y}–{to_y})</h3>
  <img src="data:image/png;base64,{b64}" alt="Alluvial Sankey diagram"/>
  <p class="chart-caption">
    Full alluvial (Sankey) diagram showing all land cover transitions including stable
    (same-class) flows. Ribbon width is proportional to area in km².
    Stable ribbons are shown at higher opacity; cross-class transitions at lower opacity.
    Source: ICIMOD Nepal Land Cover · EPSG:32645 · pixel-level transition matrix.
  </p>
</div>"""
        )

    if not sections:
        return ""
    return "<h2>Charts</h2>" + "\n".join(sections)


def generate_pdf(
    job_id: str, municipality_name: str,
    result: dict, out_path: Path,
) -> None:
    from weasyprint import HTML as WP  # noqa: PLC0415

    stats_list    = result.get("statistics", [])
    matrices      = result.get("change_matrix", [])
    evidence_list = result.get("evidence", [])
    narrative     = result.get("narrative", "")
    dataset_ver   = stats_list[0]["dataset_version"] if stats_list else "landcover-v3.1"

    years = sorted({s["year"] for s in stats_list})
    year_range = f"{years[0]}–{years[-1]}" if len(years) > 1 else str(years[0]) if years else "—"

    from_year  = matrices[0]["from_year"] if matrices else (years[0] if years else 0)
    to_year    = matrices[0]["to_year"]   if matrices else (years[-1] if years else 0)
    maps_dir   = out_path.parent  # reports/{job_id}/

    maps_html = _maps_html(maps_dir, from_year, to_year, municipality_name)
    # Figure numbering: maps section occupies figures 1–2, charts start at 3
    fig_offset = maps_html.count("<h3>Figure")

    # Template.safe_substitute uses $name placeholders — immune to { } in dynamic content
    html = Template(_HTML_TEMPLATE).safe_substitute(
        municipality_name=municipality_name,
        year_range=year_range,
        dataset_version=dataset_ver,
        job_id_short=job_id[:8],
        generated_at=datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"),
        maps_section=maps_html,
        charts_section=_charts_html(stats_list, matrices, fig_offset=fig_offset),
        statistics_section=_statistics_html(stats_list),
        change_section=_change_html(matrices),
        evidence_section=_evidence_html(evidence_list),
        narrative_section=_narrative_html(narrative),
        machine_label=_MACHINE_LABEL,
    )

    out_path.parent.mkdir(parents=True, exist_ok=True)
    WP(string=html).write_pdf(str(out_path))
    logger.info("PDF report saved: %s", out_path)


# ── XLSX ──────────────────────────────────────────────────────────────────────

def generate_xlsx(
    job_id: str, municipality_name: str,
    result: dict, out_path: Path,
) -> None:
    from openpyxl import Workbook  # noqa: PLC0415
    from openpyxl.styles import Font, PatternFill, Alignment  # noqa: PLC0415

    wb = Workbook()

    stats_list    = result.get("statistics", [])
    matrices      = result.get("change_matrix", [])
    evidence_list = result.get("evidence", [])

    header_font  = Font(bold=True, color="FFFFFF")
    header_fill  = PatternFill("solid", fgColor="1A4A7A")

    def _header(ws, row: list[str]) -> None:
        ws.append(row)
        for cell in ws[ws.max_row]:
            cell.font   = header_font
            cell.fill   = header_fill
            cell.alignment = Alignment(horizontal="center")

    # ── Sheet 1: Statistics ──────────────────────────────────────────────────
    ws1 = wb.active
    ws1.title = "Statistics"
    _header(ws1, ["Year", "Class Code", "Class Name", "Area km²", "Share %", "Pixels", "Pixel Area m²", "NoData %"])
    for stat in sorted(stats_list, key=lambda s: s["year"]):
        for cls in sorted(stat["classes"], key=lambda c: c["area_km2"], reverse=True):
            ws1.append([
                stat["year"], cls["code"],
                CLASS_NAMES.get(cls["code"], cls["name"]),
                round(cls["area_km2"], 4), round(cls["share_pct"], 3),
                cls["pixels"], stat.get("pixel_area_m2", ""),
                round(stat.get("cloud_or_nodata_pct", 0), 3),
            ])

    # ── Sheet 2: Net Change ──────────────────────────────────────────────────
    ws2 = wb.create_sheet("Net Change")
    _header(ws2, ["From Year", "To Year", "Code", "Class", "Delta km²", "Delta %"])
    for m in matrices:
        for nc in m.get("net_change", []):
            ws2.append([
                m["from_year"], m["to_year"], nc["code"],
                CLASS_NAMES.get(nc["code"], nc["class_name"]),
                round(nc["delta_km2"], 4), round(nc["delta_pct"], 3),
            ])

    # ── Sheet 3: Transitions ─────────────────────────────────────────────────
    ws3 = wb.create_sheet("Transitions")
    _header(ws3, ["From Code", "From Class", "To Code", "To Class", "Area km²", "% of Source", "Priority"])
    for m in matrices:
        for t in sorted(m.get("transitions", []), key=lambda x: x["area_km2"], reverse=True):
            ws3.append([
                t["from_code"], CLASS_NAMES.get(t["from_code"], t["from_class"]),
                t["to_code"],   CLASS_NAMES.get(t["to_code"],   t["to_class"]),
                round(t["area_km2"], 4), round(t["pct_of_source"], 3),
                "Yes" if t.get("priority_flag") else "No",
            ])

    # ── Sheet 4: CAGR ────────────────────────────────────────────────────────
    ws4 = wb.create_sheet("CAGR")
    _header(ws4, ["Code", "Class", "CAGR %/yr"])
    for m in matrices[:1]:
        for entry in m.get("cagr", []):
            ws4.append([
                entry["code"],
                CLASS_NAMES.get(entry["code"], entry["class_name"]),
                round(entry["cagr_pct"], 5),
            ])

    # ── Sheet 5: Evidence ────────────────────────────────────────────────────
    ws5 = wb.create_sheet("Evidence")
    _header(ws5, ["From", "To", "Claim", "Strength", "Effect Size", "CI 95% Low", "CI 95% High", "Sources"])
    for ev in evidence_list:
        ws5.append([
            ev.get("transition_from", ""), ev.get("transition_to", ""),
            ev.get("claim", ""),           ev.get("strength", ""),
            ev.get("effect_size", ""),     ev.get("ci_95_low", ""),
            ev.get("ci_95_high", ""),      ", ".join(ev.get("sources", [])),
        ])

    # ── Sheet 6: Metadata ────────────────────────────────────────────────────
    ws6 = wb.create_sheet("Metadata")
    ws6.append(["Key", "Value"])
    ws6.append(["Municipality", municipality_name])
    ws6.append(["Job ID",       job_id])
    ws6.append(["Generated",    datetime.utcnow().isoformat()])
    ws6.append(["Machine label", _MACHINE_LABEL])

    out_path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(out_path))
    logger.info("XLSX report saved: %s", out_path)


# ── Agent ─────────────────────────────────────────────────────────────────────

class ReportAgent:
    def __init__(self, db: Session) -> None:
        self.db = db

    def build(self, job_id: str, envelope: dict) -> dict[str, str]:
        row = self.db.execute(
            text("SELECT m.name, j.result FROM jobs j JOIN municipalities m ON m.id = j.municipality_id WHERE j.id = :id"),
            {"id": job_id},
        ).first()
        if not row or not row.result:
            return {}

        municipality_name = row.name
        result            = row.result
        out_dir           = Path(settings.object_store_path) / "reports" / job_id
        out_dir.mkdir(parents=True, exist_ok=True)

        artefacts: dict[str, dict] = result.get("artefacts", {})

        # PDF
        pdf_path = out_dir / "report.pdf"
        try:
            generate_pdf(job_id, municipality_name, result, pdf_path)
            artefacts["pdf"] = {"url": f"/jobs/{job_id}/report.pdf"}
        except Exception as exc:
            logger.error("PDF generation failed: %s", exc)

        # XLSX
        xlsx_path = out_dir / "report.xlsx"
        try:
            generate_xlsx(job_id, municipality_name, result, xlsx_path)
            artefacts["xlsx"] = {"url": f"/jobs/{job_id}/report.xlsx"}
        except Exception as exc:
            logger.error("XLSX generation failed: %s", exc)

        # Persist artefact URLs
        if artefacts:
            self.db.execute(
                text(
                    "UPDATE jobs "
                    "SET result = COALESCE(result, '{}'::jsonb) || CAST(:patch AS jsonb) "
                    "WHERE id = :id"
                ),
                {"patch": json.dumps({"artefacts": artefacts}), "id": job_id},
            )
            self.db.commit()

        return artefacts
